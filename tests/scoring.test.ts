/**
 * Scoring fixtures (SPEC §7.5–7.6, §22.22): the same JSON fixtures drive the
 * TypeScript mirror (here) and the SQL engine (a generated pgTAP file).
 *
 *   UPDATE_SCORING_SQL=1 npx jest tests/scoring.test.ts   # regenerate the pgTAP file
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { scoreSequence, summarise, type ScoringStatus } from '../src/shared/scoring';

type Fixture = {
  name: string;
  description: string;
  statuses: ScoringStatus[];
  expected: { points: number[]; streakAfter: number[]; total: number; currentStreak: number; longestStreak: number };
};

const ROOT = join(__dirname, '..');
const FIXTURE_DIR = join(ROOT, 'fixtures', 'scoring');
const SQL_FILE = join(ROOT, 'supabase', 'tests', '020_scoring_fixtures.test.sql');

const fixtures: Fixture[] = readdirSync(FIXTURE_DIR)
  .filter((f) => f.endsWith('.json'))
  .sort()
  .map((f) => JSON.parse(readFileSync(join(FIXTURE_DIR, f), 'utf8')) as Fixture);

function renderSql(list: Fixture[]): string {
  const blocks = list.map((fx) => {
    const arr = `array[${fx.statuses.map((s) => `'${s}'`).join(', ')}]::public.checkin_status[]`;
    const lines = [`-- ${fx.name}: ${fx.description}`];
    if (fx.statuses.length) {
      const values = fx.expected.points.map((p, i) => `(${i + 1}, ${p}, ${fx.expected.streakAfter[i]})`).join(', ');
      lines.push(`select results_eq($$ select idx, points, streak_after from app.score_sequence(${arr}) order by idx $$, $$ values ${values} $$, '${fx.name}: points and streak per day');`);
    } else {
      lines.push(`select is_empty($$ select 1 from app.score_sequence(${arr}) $$, '${fx.name}: no rows');`);
    }
    lines.push(`select is((select coalesce(sum(points), 0)::int from app.score_sequence(${arr})), ${fx.expected.total}, '${fx.name}: total');`);
    lines.push(`select is((select coalesce(max(streak_after), 0)::int from app.score_sequence(${arr})), ${fx.expected.longestStreak}, '${fx.name}: longest streak');`);
    return lines.join('\n');
  });
  return `-- AUTO-GENERATED by tests/scoring.test.ts from fixtures/scoring/*.json — do not edit by hand.
-- Regenerate: UPDATE_SCORING_SQL=1 npx jest tests/scoring.test.ts
begin;
create extension if not exists pgtap with schema extensions;
select no_plan();

${blocks.join('\n\n')}

select * from finish();
rollback;
`;
}

describe('scoring fixtures (TypeScript mirror)', () => {
  it('has the spec fixtures', () => {
    expect(fixtures.map((f) => f.name)).toEqual(expect.arrayContaining(['spec-7-6-worked-example', 'sixty-day-cap', 'vacation-pauses-streak']));
  });

  it.each(fixtures.map((f) => [f.name, f] as const))('%s', (_name, fx) => {
    const days = scoreSequence(fx.statuses);
    expect(days.map((d) => d.points)).toEqual(fx.expected.points);
    expect(days.map((d) => d.streakAfter)).toEqual(fx.expected.streakAfter);
    expect(summarise(days)).toEqual({
      total: fx.expected.total,
      currentStreak: fx.expected.currentStreak,
      longestStreak: fx.expected.longestStreak,
    });
  });

  it('a missed day is always strictly worse than an honest slip (SPEC §5)', () => {
    const slip = summarise(scoreSequence(['clean', 'relapse']));
    const missed = summarise(scoreSequence(['clean', 'missed']));
    expect(missed.total).toBeLessThan(slip.total);
    expect(missed.currentStreak).toBe(slip.currentStreak);
  });
});

describe('scoring fixtures (SQL mirror)', () => {
  it('the generated pgTAP file is up to date with the fixtures', () => {
    const sql = renderSql(fixtures);
    if (process.env.UPDATE_SCORING_SQL) writeFileSync(SQL_FILE, sql);
    expect(existsSync(SQL_FILE)).toBe(true);
    expect(readFileSync(SQL_FILE, 'utf8')).toBe(sql);
  });
});

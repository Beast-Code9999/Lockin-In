/**
 * Generates Lockin' In's placeholder pixel art.
 *
 *   npm run gen:art                         # write assets + manifest + registry
 *   npm run gen:art -- --preview out.png    # also write a contact sheet for eyeballing
 *
 * Outputs
 *   assets/pixel/<key>.png (+ @2x, @3x)    nearest-neighbour upscales, crisp at every density
 *   assets/pixel/manifest.json              key → file, grid size, base dp, category
 *   src/ui/pixelAssets.generated.ts         typed require() registry used by the app (and widget)
 *   assets/images/*                         app icon, adaptive icon layers, splash
 *
 * Swapping in real art: replace the PNGs (same names, same @2x/@3x set) and set
 * "custom": true on that entry in manifest.json — the generator will then leave it alone.
 */
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

import { PixelCanvas, dither, rgba, withAlpha } from './art/canvas.ts';
import { BUBBLE, BUBBLE_DARK, BUBBLE_LIGHT, DEEP, FIRE, WHITE } from './art/palette.ts';
import { toPng, writePng } from './art/render.ts';
import { allSprites, padlock, type SpriteDef } from './art/sprites.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PIXEL_DIR = join(ROOT, 'assets/pixel');
const IMAGES_DIR = join(ROOT, 'assets/images');
const MANIFEST = join(PIXEL_DIR, 'manifest.json');
const REGISTRY = join(ROOT, 'src/ui/pixelAssets.generated.ts');
const SCALES = [1, 2, 3] as const;

type ManifestEntry = {
  file: string;
  grid: [number, number];
  baseDp: number;
  category: string;
  custom: boolean;
};
type Manifest = { version: 1; generatedBy: string; note: string; assets: Record<string, ManifestEntry> };

async function readExistingManifest(): Promise<Manifest | null> {
  if (!existsSync(MANIFEST)) return null;
  return JSON.parse(await readFile(MANIFEST, 'utf8')) as Manifest;
}

function scaleFor(sprite: SpriteDef): number {
  const s = sprite.baseDp / sprite.canvas.w;
  if (!Number.isInteger(s)) throw new Error(`${sprite.key}: baseDp ${sprite.baseDp} is not a multiple of grid ${sprite.canvas.w}`);
  return s;
}

async function writeSprites(sprites: SpriteDef[], previous: Manifest | null): Promise<Manifest> {
  const assets: Record<string, ManifestEntry> = {};
  let skipped = 0;
  for (const sprite of sprites) {
    const file = `${sprite.key}.png`;
    const custom = previous?.assets[sprite.key]?.custom === true;
    assets[sprite.key] = {
      file,
      grid: [sprite.canvas.w, sprite.canvas.h],
      baseDp: sprite.baseDp,
      category: sprite.category,
      custom,
    };
    if (custom) {
      skipped++;
      continue;
    }
    const base = scaleFor(sprite);
    for (const mult of SCALES) {
      const suffix = mult === 1 ? '' : `@${mult}x`;
      await writePng(sprite.canvas, join(PIXEL_DIR, `${sprite.key}${suffix}.png`), base * mult);
    }
  }
  if (skipped) console.log(`  kept ${skipped} custom asset(s) untouched`);
  return {
    version: 1,
    generatedBy: 'scripts/gen-placeholder-art.ts',
    note: 'Replace PNGs with real art (same names + @2x/@3x) and set "custom": true to stop the generator overwriting them.',
    assets,
  };
}

async function writeRegistry(manifest: Manifest): Promise<void> {
  const lines = Object.entries(manifest.assets)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([key, e]) =>
        `  '${key}': { source: require('../../assets/pixel/${e.file}'), width: ${e.grid[0]}, height: ${e.grid[1]} },`,
    );
  const ts = `// AUTO-GENERATED by scripts/gen-placeholder-art.ts from assets/pixel/manifest.json — do not edit by hand.
// \`require\` of an image returns Metro's opaque asset id, which react-native and
// react-native-android-widget both accept as an image source.
import type { ImageRequireSource } from 'react-native';

export type PixelAsset = {
  source: ImageRequireSource;
  /** Art grid size in cells — use for aspect ratio. */
  width: number;
  height: number;
};

export const PIXEL_ASSETS = {
${lines.join('\n')}
} as const satisfies Record<string, PixelAsset>;

export type PixelAssetKey = keyof typeof PIXEL_ASSETS;
`;
  await writeFile(REGISTRY, ts);
}

// --- App icon, adaptive icon layers, splash ---------------------------------

function iconBackground(size: number, opts: { bubbles: boolean }): PixelCanvas {
  const c = new PixelCanvas(size, size);
  for (let y = 0; y < size; y++)
    for (let x = 0; x < size; x++) {
      // Diagonal light: brighter top-left, deeper bottom-right, ordered-dithered bands.
      const t = 1 - (x + y) / (2 * size);
      c.set(x, y, BUBBLE_DARK);
      if (dither(x, y, t * 1.15)) c.set(x, y, BUBBLE);
      if (dither(x + 1, y + 2, (t - 0.45) * 1.6)) c.set(x, y, BUBBLE_LIGHT);
    }
  if (opts.bubbles) {
    const k = size / 108;
    const bubble = (cx: number, cy: number, r: number) => {
      c.ring(cx * k, cy * k, r * k, Math.max(1, Math.round(k * 1.6)), withAlpha(WHITE, 0.32));
      c.disc((cx - r * 0.35) * k, (cy - r * 0.35) * k, Math.max(1, r * 0.22 * k), withAlpha(WHITE, 0.7));
    };
    bubble(24, 26, 7);
    bubble(86, 22, 4.5);
    bubble(84, 84, 8);
    bubble(20, 86, 3.5);
  }
  return c;
}

async function writeAppIcons(): Promise<void> {
  const lock = padlock();

  // iOS / generic icon: 128-cell grid × 8 = 1024px, padlock at ×3 centred.
  const icon = iconBackground(128, { bubbles: true });
  icon.draw(lock, 28, 26, 3);
  await writePng(icon, join(IMAGES_DIR, 'icon.png'), 8);

  // Android adaptive icon: 108-cell grid × 10 = 1080px. Keep the padlock inside the 66-cell safe zone.
  await writePng(iconBackground(108, { bubbles: true }), join(IMAGES_DIR, 'android-icon-background.png'), 10);
  const fg = new PixelCanvas(108, 108);
  fg.draw(lock, 30, 29, 2);
  await writePng(fg, join(IMAGES_DIR, 'android-icon-foreground.png'), 10);
  // Monochrome (Android themed icons): white silhouette with the flame keyhole cut out.
  const fire = new Set(Object.values(FIRE).map((c) => rgba(c).slice(0, 3).join(',')));
  const mono = fg.clone().clip((x, y) => !fire.has(fg.get(x, y).slice(0, 3).join(',')) || fg.get(x, y)[3] === 0);
  await writePng(mono.tint(WHITE), join(IMAGES_DIR, 'android-icon-monochrome.png'), 10);

  // Splash: padlock alone (the splash background colour comes from app.config.ts).
  await writePng(lock, join(IMAGES_DIR, 'splash-icon.png'), 20);
}

// --- Contact sheet (dev aid) -------------------------------------------------

async function writePreview(sprites: SpriteDef[], out: string): Promise<void> {
  const cell = 120;
  const cols = 8;
  const byKey = new Map(sprites.map((s) => [s.key, s]));
  const composites: string[][] = [
    ['avatar/rank/rookie', 'avatar/base/blaze'],
    ['avatar/rank/grinder', 'avatar/base/frost'],
    ['avatar/rank/locked-in', 'avatar/base/volt'],
    ['avatar/rank/disciplined', 'avatar/base/shade'],
    ['avatar/rank/monk-mode', 'avatar/base/sprout'],
    ['avatar/rank/final-boss', 'avatar/base/nova'],
    ['avatar/rank/disciplined', 'avatar/base/ace', 'avatar/state/clown'],
    ['avatar/rank/grinder', 'avatar/base/ghost', 'avatar/state/chicken'],
    ['avatar/rank/locked-in', 'avatar/base/blaze', 'avatar/state/jail'],
    ['avatar/rank/monk-mode', 'avatar/base/nova', 'avatar/state/shield'],
  ];
  const tiles: Array<{ input: Buffer; left: number; top: number }> = [];
  const items: Array<PixelCanvas> = [];
  for (const layers of composites) {
    const c = new PixelCanvas(24, 24);
    for (const key of layers) {
      const s = byKey.get(key);
      if (s) c.draw(s.canvas);
    }
    items.push(c);
  }
  items.push(...sprites.filter((s) => s.key !== 'fx/glow').map((s) => s.canvas));
  for (const [i, canvas] of items.entries()) {
    const scale = Math.max(1, Math.floor((cell - 16) / Math.max(canvas.w, canvas.h)));
    const png = await toPng(canvas, scale);
    const size = canvas.w * scale;
    tiles.push({ input: png, left: (i % cols) * cell + Math.floor((cell - size) / 2), top: Math.floor(i / cols) * cell + Math.floor((cell - canvas.h * scale) / 2) });
  }
  const rows = Math.ceil(items.length / cols);
  await sharp({ create: { width: cols * cell, height: rows * cell, channels: 4, background: DEEP } })
    .composite(tiles)
    .png()
    .toFile(out);
  console.log(`  preview → ${out}`);
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  const previewAt = args.indexOf('--preview');
  const preview = previewAt >= 0 ? args[previewAt + 1] : undefined;

  const sprites = allSprites();
  const seen = new Set<string>();
  for (const s of sprites) {
    if (seen.has(s.key)) throw new Error(`Duplicate sprite key ${s.key}`);
    seen.add(s.key);
  }

  console.log(`Generating ${sprites.length} sprites…`);
  const manifest = await writeSprites(sprites, await readExistingManifest());
  await writeFile(MANIFEST, JSON.stringify(manifest, null, 2) + '\n');
  await writeRegistry(manifest);
  await writeAppIcons();
  if (preview) await writePreview(sprites, preview);
  console.log('Done ✨');
}

await main();
